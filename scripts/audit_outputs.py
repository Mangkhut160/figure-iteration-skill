#!/usr/bin/env python3
"""Audit the files of a figure before they are handed over (system Python with PyMuPDF; read-only except --svg).

  python audit_outputs.py --pdf X --pptx Y --png Z [--svg A ...] [--page 300x180] [--sizes 6,7,8] [--min-ppi 300]
                          [--max-mb 10] [--forbid WORD[,WORD...]] [--forbid-authors-of SAVED.pptx]
Checks:
 1. --svg: removes the tool comments figgenie's embed_fonts.py leaves (the only write this script does), then scans the file;
 2. PDF: one page (of --page W x H pt when given; Chromium rounds the page to CSS pixels, 0.75 pt, so a width that is not a
    multiple of 0.75 pt comes out up to 0.37 pt off and fails the 0.3 pt tolerance), no Type 3 font, every font embedded, text
    sizes only those of --sizes (not checked when it is not given: take them from the paper's profile), every placed bitmap
    at least --min-ppi, file size at most --max-mb when given; the metadata is printed and a non-empty field is a warning
    (python pdf_clean.py blanks it);
 3. every file: no trace of the pipeline (figgenie, nature-figure, python-pptx) and no local user name; --forbid adds
    words (comma separated or repeated: tool, vendor, institution names or phrases such as 'generated by', whole words), and --forbid-authors-of adds the
    creator / last-modified-by names found in a deck the user saved (the editor writes the account name there; it may differ
    from the login name); pptx: dc:creator and cp:lastModifiedBy empty, and Company / Manager of app.xml empty (PowerPoint
    writes the organisation there); custom document properties are listed.
Exit status 1 if any check fails. A hit of the attribution scan can be a word the figure really shows: read it in context.
"""
import collections
import getpass
import os
import re
import struct
import sys
import zipfile

import fitz

failed = []


def report(ok, text):
    print(('ok    ' if ok else 'FAIL  ') + text)
    if not ok:
        failed.append(text)


def pattern(extra):
    # traces of the pipeline itself, plus the local login name; names of AI products or vendors are NOT in the default list (a
    # figure may legitimately mention them): add them with --forbid / FIG_FORBID when the paper's rules say so
    words = [r'figgenie', r'nature-figure', r'python-pptx', re.escape(getpass.getuser())]
    words += [r'(?<![A-Za-z0-9])' + re.escape(w) + r'(?![A-Za-z0-9])' for w in extra]
    return re.compile('|'.join(words), re.I)


def scan(pat, name, text):
    hits = sorted({m.group(0).lower() for m in pat.finditer(text)})
    report(not hits, f'{name}: no attribution / user name' + (f'  HITS {hits}' if hits else ''))


def audit_pdf(pat, path, page_wh, sizes, min_ppi, max_mb):
    doc = fitz.open(path)
    page = doc[0]
    w, h = page.rect.width, page.rect.height
    ok = len(doc) == 1 and (page_wh is None or (abs(w - page_wh[0]) < 0.3 and abs(h - page_wh[1]) < 0.3))
    report(ok, f'PDF: {len(doc)} page(s), {w:.2f} x {h:.2f} pt' + (f' (want {page_wh[0]:g} x {page_wh[1]:g})' if page_wh else ''))
    all_fonts = page.get_fonts(full=True)
    fonts = sorted({(f[3].split('+')[-1], f[2]) for f in all_fonts})
    report(bool(fonts) and all(t != 'Type3' for _, t in fonts), f'PDF fonts {fonts} (none is Type 3)')
    loose = sorted({f[3].split('+')[-1] for f in all_fonts if f[1] in ('n/a', '')})
    report(not loose, 'PDF fonts: every one is embedded' + (f'  NOT EMBEDDED {loose}' if loose else ''))
    got = collections.Counter()
    for b in page.get_text('dict')['blocks']:
        for line in b.get('lines', []):
            for sp in line['spans']:
                got[round(sp['size'], 1)] += len(sp['text'])
    if sizes:
        report(set(got) <= set(sizes), f'PDF text sizes (pt: chars) {dict(sorted(got.items()))}, allowed {sorted(sizes)}')
    else:
        print(f'note  PDF text sizes (pt: chars) {dict(sorted(got.items()))}: not checked, no --sizes given (FIG_SIZES in figure.env)')
    ppi = [min(img[2] / (r.width / 72), img[3] / (r.height / 72))
           for img in page.get_images(full=True) for r in page.get_image_rects(img[0]) if r.width > 0 and r.height > 0]
    if ppi:
        report(min(ppi) >= min_ppi, f'PDF: {len(ppi)} placed bitmaps, lowest {min(ppi):.0f} ppi (>= {min_ppi})')
    else:
        report(True, 'PDF: no placed bitmaps')
    if max_mb:
        mb = os.path.getsize(path) / 1e6
        report(mb <= max_mb, f'PDF file size {mb:.2f} MB (<= {max_mb:g})')
    meta = {k: v for k, v in doc.metadata.items() if v and k not in ('creationDate', 'modDate', 'format', 'encryption', 'trapped')}
    print(('warn  ' if meta else '      ') + f'PDF metadata: {meta}' + ('   (python pdf_clean.py <pdf> blanks it)' if meta else ''))
    scan(pat, 'PDF (raw bytes)', open(path, 'rb').read().decode('latin-1'))


def audit_pptx(pat, path):
    z = zipfile.ZipFile(path)
    scan(pat, f'{os.path.basename(path)} ({len(z.namelist())} parts)',
         '\n'.join(z.read(n).decode('utf-8', 'ignore') for n in z.namelist() if n.endswith(('.xml', '.rels'))))
    core = z.read('docProps/core.xml').decode('utf-8', 'ignore')
    empty = all(re.search(rf'<{t}\s*/>|<{t}>\s*</{t}>', core) or not re.search(rf'<{t}[\s>]', core) for t in ('dc:creator', 'cp:lastModifiedBy'))
    report(empty, 'pptx core.xml: creator and last-modified-by empty')
    app = z.read('docProps/app.xml').decode('utf-8', 'ignore') if 'docProps/app.xml' in z.namelist() else ''
    org = {t: re.findall(rf'<{t}>([^<]+)</{t}>', app) for t in ('Company', 'Manager')}
    org = {t: v for t, v in org.items() if v}
    report(not org, 'pptx app.xml: Company and Manager empty' + (f'  HITS {org}' if org else ''))
    if 'docProps/custom.xml' in z.namelist():
        names = re.findall(r'name="([^"]+)"', z.read('docProps/custom.xml').decode('utf-8', 'ignore'))
        print(f'note  pptx custom document properties: {names}')


def audit_png(pat, path):
    data = open(path, 'rb').read()
    pos, texts = 8, []
    while pos < len(data):
        ln, typ = struct.unpack('>I4s', data[pos:pos + 8])
        if typ in (b'tEXt', b'iTXt', b'zTXt', b'eXIf'):
            texts.append(data[pos + 8:pos + 8 + ln].decode('latin-1'))
        pos += 12 + ln
    scan(pat, f'{os.path.basename(path)} ({len(texts)} text chunks)', '\n'.join(texts))


def main(argv):
    files = {'--pdf': [], '--pptx': [], '--png': [], '--svg': []}
    page_wh, sizes, min_ppi, max_mb, extra = None, None, 300, None, []
    i = 0
    while i < len(argv):
        a = argv[i]
        if i + 1 >= len(argv):
            raise SystemExit(__doc__)
        v = argv[i + 1]
        if a in files:
            files[a].append(v)
        elif a == '--page':
            page_wh = tuple(float(x) for x in v.lower().split('x'))
        elif a == '--sizes':
            sizes = [round(float(x), 1) for x in v.split(',')]
        elif a == '--min-ppi':
            min_ppi = float(v)
        elif a == '--max-mb':
            max_mb = float(v)
        elif a == '--forbid':
            extra += [w.strip() for w in v.split(',') if w.strip()]
        elif a == '--forbid-authors-of':
            core = zipfile.ZipFile(v).read('docProps/core.xml').decode('utf-8', 'ignore')
            names = {m.strip() for t in ('dc:creator', 'cp:lastModifiedBy') for m in re.findall(rf'<{t}>([^<]+)</{t}>', core)}
            extra += sorted(n for n in names if len(n) >= 3)
        else:
            raise SystemExit(__doc__)
        i += 2
    if not any(files.values()):
        raise SystemExit(__doc__)
    pat = pattern(extra)
    for svg in files['--svg']:
        s = open(svg, encoding='utf-8').read()
        n = len(re.findall(r'<!--[^>]*figgenie[^>]*-->', s, flags=re.I))
        if n:
            open(svg, 'w', encoding='utf-8').write(re.sub(r'<!--[^>]*figgenie[^>]*-->', '', s))
            print(f'tool comments removed from {os.path.basename(svg)}: {n}')
        scan(pat, os.path.basename(svg), open(svg, encoding='utf-8').read())
    for p in files['--pdf']:
        audit_pdf(pat, p, page_wh, sizes, min_ppi, max_mb)
    for p in files['--pptx']:
        audit_pptx(pat, p)
    for p in files['--png']:
        audit_png(pat, p)
    print('\nALL OK' if not failed else f'\n{len(failed)} CHECK(S) FAILED')
    sys.exit(1 if failed else 0)


if __name__ == '__main__':
    main(sys.argv[1:])
